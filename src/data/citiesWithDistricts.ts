const PRIORITY_CITIES = ["Москва", "Московская область", "Санкт-Петербург", "Ленинградская область"];

export const getSortedCities = (): string[] => {
  const allCities = Object.keys(citiesWithDistricts);
  const otherCities = allCities
    .filter(city => !PRIORITY_CITIES.includes(city))
    .sort((a, b) => a.localeCompare(b, 'ru'));
  
  return [...PRIORITY_CITIES, ...otherCities];
};

export const getCityOptions = (): { value: string; label: string }[] => {
  return getSortedCities().map(city => ({
    value: city,
    label: city
  }));
};

